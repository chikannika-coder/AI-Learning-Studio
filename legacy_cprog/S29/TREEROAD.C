typedef long Fixedpoint;
#define FIXED_TO_INT(a)   (int)((a) >> 16)
#define INT_TO_FIXED(a)   ((Fixedpoint)(a) << 16)
#define FixedDiv(a, b)    (Fixedpoint)(a / ((b + 0x8000) >> 16))
typedef struct {
     Fixedpoint x, y, z;
} POINT;
typedef struct {
     int x, y;
} POINT_2D;
Fixedpoint  Speed, Speed1, CheckZ;
#define MAX_STARS 80
#define NTreeBall  15
#define SPEED 4
POINT stars[MAX_STARS];
BYTE TYPE[MAX_STARS], *CAR, Floor = 0;
int CAdd, SCORE = 0, NUMCAR = 5;
void MakePoint(int x, int y, int z, POINT *p)
{
     p->x = INT_TO_FIXED(x);
     p->y = INT_TO_FIXED(y);
     p->z = INT_TO_FIXED(z);
}
void ThreeD2TwoD(POINT *threeD, POINT_2D *twoD)
{
     twoD->x = (int)((FixedDiv(threeD->x, -threeD->z) << 8) >> 16);
     twoD->y = (int)((FixedDiv(threeD->y, -threeD->z) << 8) >> 16);
}
void InitPoint(int i)
{
     if(i < NTreeBall )
          MakePoint(random(80) - 40, 3, -68, &stars[i]);
     else
          MakePoint(random(80) - 40, -random(20), -68, &stars[i]);
}
void AnimateRoad(void)
{
     #define SWAP(a,b) { temp = a; a = b; b = temp; }
     POINT_2D p, n[NTreeBall];
     int SIZE[NTreeBall], i, j, color, temp;
     for (i = 0; i < MAX_STARS; i++) {
          stars[i].z = (i < NTreeBall ) ? stars[i].z + Speed1 :
                    stars[i].z + Speed;
          ThreeD2TwoD(&stars[i], &p);
          if (p.x < -180 || p.x > 140 || p.y < -110 || p.y > 100 ||
                    stars[i].z >= CheckZ) {
               InitPoint(i);
               ThreeD2TwoD(&stars[i], &p);
          }
          color = FIXED_TO_INT(stars[i].z) + 67;
          if(i < NTreeBall) {
               n[i].x = p.x + 160;
               n[i].y = p.y + 105;
               SIZE[i] = color;
			   TYPE[i] = i % 5;
               if(n[i].x > 120 && n[i].x < 180 &&
                         p.y > 60 && p.y < 100) {
                    InitPoint(i);
                    if(!TYPE[i]) {
                         for(temp = 1; temp < 30; temp ++) {
                              sound(temp * 80 + 2000);
                              delay(10); nosound(); }
                         SCORE += 10;
                    }
                    else {
                         for(temp = 1; temp < 40; temp ++) {
                              sound(random(30) * 60 + 400);
                              delay(10); nosound(); }
                         NUMCAR--;
                    }
               }
          }
          else
               PutPixel(p.x + 160, p.y + 110, color + 71);
     }
     for(i = 0; i < NTreeBall - 1; i++)
          for(j = i + 1; j < NTreeBall; j++)
               if (SIZE[i] >= SIZE[j]) {
                    SWAP(SIZE[i], SIZE[j]);
                    SWAP(n[i].x, n[j].x);
                    SWAP(n[i].y, n[j].y);
                    SWAP(TYPE[i], TYPE[j]);
               }
     for(i = 0; i < NTreeBall; i++) {
          if(TYPE[i])
               PutScale(n[i].x, n[i].y - (SIZE[i] << 1), Tree,
                    SIZE[i], SIZE[i] << 1);
          else
               PutScale(n[i].x, n[i].y - (SIZE[i] >> 1), BallBitmap,
               SIZE[i] >> 1, SIZE[i] >> 1);
     }
     PutScale(130 + CAdd, 150, CAR, 60, 40); /* Car Scale 2X */
     for(i = 0; i < NUMCAR; i++)
          PutScale(i * 21 + 1, 187, CAR, 20, 12);
     if(++Floor > 1 ) { Floor = 0; CirclePal(); }
}
