void PutPixel(int i, int j, int color)
{
	if(i < 640 && j < 480 && i >= 0 && j >= 0)
		putpix(i, j, color);
}

void setpal(void)
{
	BYTE *ptr, i, j, r, g, b;
	ptr = Palette;
	outp(0x3c8, 1);
	for(i = 0; i < 93; i++)
		outp(0x3c9, *ptr++);
	ptr = col;
	for(j = 0; j < 7; j++) {
		r = *ptr++;
		g = *ptr++;
		b = *ptr++;
		for(i = 0; i < 32; i++) {
			outp(0x3c9, i * r);
			outp(0x3c9, i * g);
			outp(0x3c9, i * b);
		}
	}
}
void BarClip(int x0, int y0, int x1, int y1, BYTE color)
{
	int i, j;
	for(j = y0; j < y1; j++)
		for(i = x0; i < x1; i++)
			PutPixel(i, j, color);

}
void putscale2x(int x, int y, BYTE *img,int sign)
{
	int i, j, width, height, color;
	BYTE *ptr;
	ptr = img;
	width  = 2 * (*ptr++) + x;
	height = 2 * (*ptr++) + y;
	for(j = y; j < height; j += 2) {
		for(i = x; i < width; i += 2){
			color = *ptr++;
			if(color || !sign)
			{
				PutPixel(i, j, color);
				PutPixel(i + 1,j, color);
				PutPixel(i, j + 1, color);
				PutPixel(i + 1, j + 1, color);
			}
		}
	}
}
void putballon(int x,int y,int color)
{
	int i, j, k, width, height;
	BYTE *ptr, *ptr1;
	ptr = Ballon;
	width = *ptr++;
	height = *ptr++;
	ptr1 = Ballon1;
	*ptr1++ = width;
	*ptr1++ = height;
	for(j = 0; j < height; j++){
		for(i = 0; i < width; i++){
			if(*ptr != 0 && color != 0)
				*ptr1 = *ptr + (color << 5);
			else
				*ptr1 = *ptr;
			ptr++; ptr1++;
		}
	}
	putscale2x(x, y, Ballon1, 1);
	k = random(4) + 4;
	for(i = 0; i < 36; i++)
		PutPixel(x + 17 + (i / k), y + 38 + i, (color << 5) + 8);
}
