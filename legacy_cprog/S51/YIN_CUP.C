void InitMode13(void)
{
     int i;

     _AX = 0x13;
     geninterrupt(0x10);
     for(i = 0; i < 200; i++)
     LINE_Y[i] = i * 320;
     MemLength = 320 * 200;
     PageStart = malloc(MemLength);
     memset(PageStart, 0, MemLength);
}
void CloseGraph(void)
{
     _AX = 3;
     geninterrupt(0x10);
     free(PageStart);
}

void PutPixel(int x, int y, BYTE color)
{    /* put pixel */
     if(x < 0 || x > 319 || y < 0 || y > 199) return;
     *(PageStart + LINE_Y[y] + x ) = color;
}
void Bar(int x0, int y0, int x1, int y1, int color)
{    /* color bar */
     int i, j;
     for(j = y0; j < y1; j++)
     for(i = x0; i < x1; i++)
     PutPixel(i, j, color);
}
void Rec(int x0, int y0, int x1, int y1, int color)
{    /* rectangle */
     int i;

     for(i = y0; i <= y1; i++) {
          PutPixel(x0, i, color);
          PutPixel(x1, i, color);
     }
     for(i = x0; i <= x1; i++) {
          PutPixel(i, y0, color);
          PutPixel(i, y1, color);
     }
}
void PutSprite(int x0, int y0, BYTE *ptr)
{
     int i, j, x1, y1;
     x1 = x0 + *ptr++; y1 = y0 + *ptr++;
     for(j = y0; j < y1; j++)
          for(i = x0; i < x1; i++, ptr++)
               if(i >= 0 && i < 320 &&
                    j >= 0 && j < 200 && *ptr )
                    *(PageStart + LINE_Y[j]  + i ) = *ptr;
}

