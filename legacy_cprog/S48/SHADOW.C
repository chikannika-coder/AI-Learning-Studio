void MakeShadowTable (BYTE *pal)
{
        typedef struct {
		BYTE r, g, b;
	} color;
	#define S_BLINK 0.5

	long ired, igreen, iblue, absr, absg, absb;
	short col, findcol;

	unsigned long lowest;
	unsigned char bestfit;
	unsigned long coldif;
	color *palette;
	palette = (color *) pal;

	 for (col = 0; col < 256; col++) {
		ired   = (long)palette[col].r * S_BLINK;
		igreen = (long)palette[col].g * S_BLINK;
		iblue  = (long)palette[col].b * S_BLINK;
		lowest = 655350;
		for  (findcol = 0; findcol < 256; findcol++) {
			absr = abs ( (long)palette[findcol].r - ired);
			absg = abs ( (long)palette[findcol].g - igreen);
			absb = abs ( (long)palette[findcol].b - iblue);

			coldif = absr + absg + absb;
			if  ((coldif < lowest) && (findcol != col)) {
				lowest = coldif;
				bestfit = findcol;
			}
		}
		ShadowTable[col] = bestfit;
	}
}

